const q = (
  id: string,
  n: number,
  type: string,
  prompt: string,
  answerOrOptions: string | string[],
  explanationOrAnswer: string,
  maybeExpl?: string | Partial<Question>,
  extra?: Partial<Question>,
): Question => {
  if (typeof maybeExpl === 'string') {
    return {
      id,
      n,
      type,
      prompt,
      answer: explanationOrAnswer,
      explanation: maybeExpl,
      options: Array.isArray(answerOrOptions) ? answerOrOptions : undefined,
      ...extra,
    }
  }
  return {
    id,
    n,
    type,
    prompt,
    answer: answerOrOptions,
    explanation: explanationOrAnswer,
    ...(maybeExpl ?? {}),
  }
}

